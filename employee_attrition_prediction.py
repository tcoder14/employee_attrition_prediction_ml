"""DROP USELESS COLUMNS"""

cols_to_drop = ['id', 'EmployeeCount', 'Over18', 'StandardHours']
df = df.drop(columns = cols_to_drop, errors = 'ignore')

"""ENCODE CATEGORICAL VARIABLES"""

categorical_cols = df.select_dtypes(include=['object']).columns
for col in categorical_cols:
  le = LabelEncoder()
  df[col] = le.fit_transform(df[col])

"""SEPARATE INPUT (x) AND OUTPUT (Y)"""

X = df.drop('Attrition', axis=1)
y = df['Attrition']

"""FEATURE SCALING"""

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

"""SPLITTING BETWEEN TRAIN AND TEST DATA"""

X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42, stratify=y)

"""KNN"""

knn = KNeighborsClassifier(n_neighbors=5)
knn.fit(X_train, y_train)
knn_preds = knn.predict(X_test)

"""DECISION TREE"""

dt = DecisionTreeClassifier(random_state=42, max_depth=5)
dt.fit(X_train, y_train)
dt_preds = dt.predict(X_test)

"""MLP"""

nn = MLPClassifier(hidden_layer_sizes=(64, 32), max_iter=1000, random_state=42)
nn.fit(X_train, y_train)
nn_preds = nn.predict(X_test)

"""K-MEANS CLUSTERING"""

kmeans = KMeans(n_clusters=2, random_state=42, n_init=10)
clusters = kmeans.fit_predict(X_scaled)

"""COMPARISON ANALYSIS"""

models = ['KNN', 'Decision Tree', 'Neural Network']
predictions = [knn_preds, dt_preds, nn_preds]
classifiers = [knn, dt, nn]

accuracies, precisions, recalls = [], [], []

for i in range(3):
    accuracies.append(accuracy_score(y_test, predictions[i]))
    precisions.append(precision_score(y_test, predictions[i], zero_division=0))
    recalls.append(recall_score(y_test, predictions[i]))

    print(f"\n--- {models[i]} Confusion Matrix ---")
    print(confusion_matrix(y_test, predictions[i]))

"""BAR CHART COMPARING METRICES"""

x_axis = np.arange(len(models))
plt.figure(figsize=(10,6))
plt.bar(x_axis - 0.2, accuracies, 0.2, label='Accuracy', color='skyblue')
plt.bar(x_axis, precisions, 0.2, label='Precision', color='lightgreen')
plt.bar(x_axis + 0.2, recalls, 0.2, label='Recall', color='salmon')
plt.xticks(x_axis, models)
plt.legend()
plt.title('Prediction Metrics Comparison (Class 1 Focus)')
plt.ylabel('Score')
plt.show()

"""ROC CURVE AND AUC"""

plt.figure(figsize=(8,6))
for i in range(3):
    y_prob = classifiers[i].predict_proba(X_test)[:, 1]
    fpr, tpr, _ = roc_curve(y_test, y_prob)
    roc_auc = auc(fpr, tpr)
    plt.plot(fpr, tpr, label=f'{models[i]} (AUC = {roc_auc:.2f})')

plt.plot([0, 1], [0, 1], 'k--', label='Random Chance')
